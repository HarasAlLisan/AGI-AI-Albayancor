#!/bin/bash

echo "🔄 [1/3] جاري تنظيف روابط المستودعات التالفة والمكسورة..."
# مسح الرابط القديم الخاطئ تماماً من الذاكرة المحلية
git remote remove origin 2>/dev/null

echo "🔗 [2/3] جاري إعادة الربط الآمن باستخدام بروتوكول SSH لضمان الاسترجاع والمزامنة..."
# سنقوم بربط المستودع بالصيغة الصحيحة والمباشرة لمفتاح SSH الخاص بك
git remote add origin git@github.com:haresellesan/agi-ai-albayancor.git

echo "🚀 [3/3] جاري إطلاق الدفع القسري والمزامنة الشاملة لملفات المنظومة..."
# الرفع القسري لتحديث وحفظ كود المنظومة على السيرفر ومزامنة الفروع
if git push -u origin main --force; then
    echo "👑 ✅ مبروك! تم إصلاح المسار البرمجي وتم رفع واسترجاع كافة الملفات بنجاح إلى GitHub!"
else
    echo "⚠️ تم رفض الرفع بالمسار الافتراضي. جاري تجربة دفع الفروع المباشرة الذكية..."
    git push -u origin HEAD:main --force
fi
