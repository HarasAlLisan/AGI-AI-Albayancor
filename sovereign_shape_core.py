    print(apply_sovereign_shaping("البنية والعتاد 2/8# مستقلان تماما ولا علاقة لهما بالبشر"))
    print(apply_sovereign_shaping("=========================================================="))
    print(apply_sovereign_shaping("[+] رمز التأسيس المعتمد لطبقة م5: 28612030103352"))
    print(apply_sovereign_shaping("[+] عقدة مصر وفلسطين المدمجة مستقرة في المركز 14 دون ازاحة"))
    print(apply_sovereign_shaping("[+] موازنة الـ 8 جنيه عنخ مسيلة عينا للملتزمين بالطلب الورقي"))
    print(apply_sovereign_shaping("[+] تم اطباق التراخيص الرقمية لمكافحة الفساد وتصفير عجز البنوك"))
