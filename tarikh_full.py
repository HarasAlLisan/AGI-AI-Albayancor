chain = [
    (2026, 309, "الآن"),
    (1717, 309, ""),
    (1408, 309, ""),
    (1099, 309, "رخص فيض الاسلام"),
    (790, 128, "أول الملك العضوض"),
    (662, 30, "خلافه"),
    (632, 23, "نزول اقرأ"),
    (609, 40, "ميلاد"),
]

y = 2026
print(f"{y} = الآن")
for year, minus, label in chain:
    if y != year: continue
    ny = y - minus
    print(f"{y} - {minus} = {ny}  {label}")
    y = ny

print(f"\nالنهاية: {y} = 571 ميلاد")
print(f"الدستور الثابت فوقها كلها: 6236")
