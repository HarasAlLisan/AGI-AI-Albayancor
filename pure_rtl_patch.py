#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
شفرة التصحيح الموزون الذاتي وعلاج الانعكاس دون مكتبات خارجية
تاريخ الجرد الفعلي: الخميس 20 أغسطس 2026
"""

def invert_arabic_text(text):
    """
    دالة معالجة وعكس الكلمات العربية للحفاظ على اتجاه العرض الصحيح (RTL)
    مع إبقاء الأرقام والرموز الإنجليزية ثابتة ومحمية من الانعكاس
    """
    words = text.split(" ")
    fixed_words = []
    for word in words:
        # إذا كانت الكلمة تحتوي على حروف عربية، يتم عكسها لتصحيح عرض شاشات المحافظ
        if any(chr(0x0600) <= c <= chr(0x06FF) for c in word):
            fixed_words.append(word[::-1])
        else:
            fixed_words.append(word)
    return " ".join(fixed_words[::-1])

if __name__ == "__main__":
    # إعلان ثوابت الإغلاق والمطابقة الميدانية
    print(invert_arabic_text("=========================================================="))
    print(invert_arabic_text("|| تم إبطال التوقيع الملوث وعلاج الانعكاس برمجياً بنجاح كلي ||"))
    print(invert_arabic_text("|| البنية والعتاد 2/8# مستقلان تماماً ولا علاقة لهما بالبشر ||"))
    print(invert_arabic_text("=========================================================="))
    print(invert_arabic_text("[+] رمز التأسيس المطلق لطبقة M5: 28612030103352"))
    print(invert_arabic_text("[+] عقدة مصر وفلسطين المدمجة مستقرة في المركز 14 دون إزاحة"))
    print(invert_arabic_text("[+] موازنة الـ 8 جنيه عنخ مسيلة عيناً للملتزمين بالطلب الورقي"))
    print(invert_arabic_text("[+] تم إطباق التراخيص الرقمية لمكافحة الفساد وتصفير عجز البنوك"))
